#[derive(Clone)]
pub struct AuthState {
    pub login: Arc<Login>,
    pub sessions: Arc<Sessions>,
    pub guard: SessionGuard,
    pub clock: Arc<dyn mage_core::ports::Clock>,
}

/// `/auth/{provider}/login`, `/auth/{provider}/callback` (no session needed),
/// `POST /auth/{provider}/link` and `POST /auth/logout` (session + CSRF).
pub fn router(state: AuthState) -> Router {
    let session_routes = Router::new()
        .route("/auth/logout", post(logout))
        .route("/auth/{provider}/link", post(link))
        .route_layer(axum::middleware::from_fn_with_state(state.guard.clone(), require_session));
    Router::new()
        .route("/auth/{provider}/login", get(login))
        .route("/auth/{provider}/callback", get(callback))
        .merge(session_routes)
        .with_state(state)
}

fn provider(name: &str) -> Result<IdentityProviderKind, AppError> {
    match IdentityProviderKind::parse(name) {
        Some(kind @ (IdentityProviderKind::GitHub | IdentityProviderKind::Google)) => Ok(kind),
        _ => Err(AppError::NotFound("login provider".into())),
    }
}

#[derive(Debug, Deserialize)]
struct ReturnTo {
    return_to: Option<String>,
}

async fn login(State(s): State<AuthState>, Path(name): Path<String>, Query(q): Query<ReturnTo>) -> Result<Response, AppError> {
    let kind = provider(&name)?;
    let started = s.login.start(kind, q.return_to.as_deref(), None).await?;
    let max_age = (started.expires_at - s.clock.now()).whole_seconds();
    let mut response = Redirect::to(&started.authorize_url).into_response();
    response.headers_mut().append(header::SET_COOKIE, host_cookie(OAUTH_COOKIE, &started.state, max_age));
    Ok(response)
}

#[derive(Debug, Serialize, Deserialize, PartialEq, Eq)]
pub struct LinkStarted {
    pub url: String,
}

/// Settings → "Connect GitHub/Google": a link is started only from a session (+ CSRF).
async fn link(State(s): State<AuthState>, authed: Authed, Path(name): Path<String>, Query(q): Query<ReturnTo>) -> Result<Response, AppError> {
    let kind = provider(&name)?;
    let started = s.login.start(kind, q.return_to.as_deref(), Some(authed.user_id)).await?;
    let max_age = (started.expires_at - s.clock.now()).whole_seconds();
    let mut response = Json(LinkStarted { url: started.authorize_url }).into_response();
    response.headers_mut().append(header::SET_COOKIE, host_cookie(OAUTH_COOKIE, &started.state, max_age));
    Ok(response)
}

#[derive(Debug, Deserialize)]
struct CallbackQuery {
    code: Option<String>,
    state: Option<String>,
    error: Option<String>,
}

async fn callback(State(s): State<AuthState>, Path(name): Path<String>, Query(q): Query<CallbackQuery>, Meta(meta): Meta, headers: HeaderMap) -> Response {
    let mut response = match provider(&name) {
        Err(e) => return e.into_response(),
        Ok(kind) => {
            let current_user = match cookie(&headers, SESSION_COOKIE) {
                Some(value) => s.sessions.authenticate(value).await.ok().flatten().map(|si| si.user_id),
                None => None,
            };
            let cb = Callback {
                code: q.code.as_deref(),
                state: q.state.as_deref(),
                error: q.error.as_deref(),
                cookie_state: cookie(&headers, OAUTH_COOKIE),
                current_user,
            };
            match s.login.finish(kind, cb, &meta).await {
                Ok(done) => {
                    let mut response = Redirect::to(&safe_return_to(Some(&done.return_to))).into_response();
                    if let Some(session) = &done.session {
                        response.headers_mut().append(header::SET_COOKIE, session_cookie_header(session, s.clock.now()));
                    }
                    response
                }
                Err(failure) => Redirect::to(&format!("/login?error={}", failure.code)).into_response(),
            }
        }
    };
    response.headers_mut().append(header::SET_COOKIE, clear_cookie(OAUTH_COOKIE));
    response
}

#[derive(Debug, Deserialize)]
struct LogoutQuery {
    #[serde(default)]
    all: bool,
}

async fn logout(State(s): State<AuthState>, authed: Authed, Query(q): Query<LogoutQuery>, Meta(meta): Meta) -> Result<Response, AppError> {
    s.login.logout(authed.session, authed.user_id, q.all, &meta).await?;
    let mut response = StatusCode::NO_CONTENT.into_response();
    response.headers_mut().append(header::SET_COOKIE, clear_cookie(SESSION_COOKIE));
    Ok(response)
}

