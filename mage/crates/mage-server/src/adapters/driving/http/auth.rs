/// State of the session middleware.
#[derive(Clone)]
pub struct SessionGuard {
    pub sessions: Arc<Sessions>,
    pub directory: Arc<Directory>,
    /// `scheme://host[:port]` of `public_url`: the only accepted `Origin` on mutations.
    pub public_origin: String,
}

fn is_mutation(method: &Method) -> bool {
    matches!(*method, Method::POST | Method::PUT | Method::PATCH | Method::DELETE)
}

fn has_body(headers: &HeaderMap) -> bool {
    headers.contains_key(header::TRANSFER_ENCODING)
        || headers.get(header::CONTENT_LENGTH).and_then(|v| v.to_str().ok()).and_then(|v| v.parse::<u64>().ok()).is_some_and(|n| n > 0)
}

/// UC2 steps 1–3: session cookie → TokenStore (401), CSRF on mutations (403), `{org}` →
/// `OrgCtx` (404). Inserts [`Authed`], [`SessionInfo`] and (for org paths) [`OrgCtx`].
pub async fn require_session(State(guard): State<SessionGuard>, mut req: Request, next: Next) -> Response {
    match authenticate(&guard, &mut req).await {
        Ok(()) => next.run(req).await,
        Err(e) => {
            let unauthenticated = matches!(e, AppError::Unauthorized);
            let mut response = e.into_response();
            if unauthenticated {
                response.headers_mut().append(header::SET_COOKIE, clear_cookie(SESSION_COOKIE));
            }
            response
        }
    }
}

async fn authenticate(guard: &SessionGuard, req: &mut Request) -> Result<(), AppError> {
    let value = cookie(req.headers(), SESSION_COOKIE).ok_or(AppError::Unauthorized)?;
    let session = guard.sessions.authenticate(value).await?.ok_or(AppError::Unauthorized)?;
    let span = tracing::Span::current();
    span.record("user_id", tracing::field::display(session.user_id));

    if is_mutation(req.method()) {
        check_csrf(guard, &session, req.headers()).await?;
    }

    let (mut parts, body) = std::mem::take(req).into_parts();
    let slug = match RawPathParams::from_request_parts(&mut parts, &()).await {
        Ok(params) => params.iter().find(|(k, _)| *k == "org").map(|(_, v)| v.to_owned()),
        Err(_) => None,
    };
    if let Some(slug) = slug {
        let access = guard.directory.access(session.user_id, &slug).await?.ok_or_else(|| AppError::NotFound("org".into()))?;
        span.record("org_id", tracing::field::display(access.org_id));
        parts.extensions.insert(OrgCtx { org_id: access.org_id, user_id: session.user_id, role: access.role });
    }
    parts.extensions.insert(Authed { user_id: session.user_id, session: session.id });
    parts.extensions.insert(session);
    *req = Request::from_parts(parts, body);
    Ok(())
}

/// Every mutation needs: `X-CSRF-Token` equal to the session's token (constant time),
/// `Origin` equal to `public_url` (if absent, `Sec-Fetch-Site: same-origin`), and
/// `Content-Type: application/json` when a body is present.
async fn check_csrf(guard: &SessionGuard, session: &SessionInfo, headers: &HeaderMap) -> Result<(), AppError> {
    match headers.get(header::ORIGIN) {
        Some(origin) => {
            if !constant_time_eq(origin.as_bytes(), guard.public_origin.as_bytes()) {
                return Err(AppError::Forbidden("cross-origin request".into()));
            }
        }
        None => {
            let same_origin = headers.get("sec-fetch-site").is_some_and(|v| v.as_bytes() == b"same-origin");
            if !same_origin {
                return Err(AppError::Forbidden("missing Origin".into()));
            }
        }
    }
    let token = headers.get(CSRF_HEADER).and_then(|v| v.to_str().ok()).ok_or_else(|| AppError::Forbidden("missing CSRF token".into()))?;
    if !guard.sessions.verify_csrf(session, token).await? {
        return Err(AppError::Forbidden("invalid CSRF token".into()));
    }
    if has_body(headers) {
        let json = headers
            .get(header::CONTENT_TYPE)
            .and_then(|v| v.to_str().ok())
            .and_then(|v| v.split(';').next())
            .is_some_and(|v| v.trim().eq_ignore_ascii_case("application/json"));
        if !json {
            return Err(AppError::Invalid("mutations take application/json bodies".into()));
        }
    }
    Ok(())
}

