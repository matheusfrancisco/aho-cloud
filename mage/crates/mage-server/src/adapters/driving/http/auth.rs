/// The session user (session groups only).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Authed {
    pub user_id: UserId,
    pub session: SessionId,
}

/// Session user + `{org}` slug → membership. Unknown org and non-member get the same 404.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct OrgCtx {
    pub org_id: OrgId,
    pub user_id: UserId,
    pub role: MemberRole,
}

impl OrgCtx {
    /// Route minimum role; below it → 403.
    pub fn require(&self, min: MemberRole) -> Result<(), AppError> {
        if self.role.at_least(min) {
            Ok(())
        } else {
            Err(AppError::Forbidden(format!("requires the {} role", role_label(min))))
        }
    }
}

fn role_label(role: MemberRole) -> &'static str {
    match role {
        MemberRole::Member => "member",
        MemberRole::Admin => "admin",
        MemberRole::Owner => "owner",
    }
}

impl<S: Send + Sync> FromRequestParts<S> for Authed {
    type Rejection = AppError;

    async fn from_request_parts(parts: &mut Parts, _state: &S) -> Result<Self, Self::Rejection> {
        parts.extensions.get::<Authed>().copied().ok_or(AppError::Unauthorized)
    }
}

impl<S: Send + Sync> FromRequestParts<S> for OrgCtx {
    type Rejection = AppError;

    async fn from_request_parts(parts: &mut Parts, _state: &S) -> Result<Self, Self::Rejection> {
        parts.extensions.get::<OrgCtx>().copied().ok_or_else(|| AppError::NotFound("org".into()))
    }
}

/// Minimum-role marker for [`RequireRole`].
pub trait MinRole: Send + Sync + 'static {
    const ROLE: MemberRole;
}

/// Marker: any member.
#[derive(Debug, Clone, Copy)]
pub struct Member;
/// Marker: Admin or Owner.
#[derive(Debug, Clone, Copy)]
pub struct Admin;
/// Marker: Owner.
#[derive(Debug, Clone, Copy)]
pub struct Owner;

impl MinRole for Member {
    const ROLE: MemberRole = MemberRole::Member;
}
impl MinRole for Admin {
    const ROLE: MemberRole = MemberRole::Admin;
}
impl MinRole for Owner {
    const ROLE: MemberRole = MemberRole::Owner;
}

/// `OrgCtx` whose role is at least `R` (`RequireRole<Admin>`); below → 403.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RequireRole<R: MinRole>(pub OrgCtx, PhantomData<R>);

impl<R: MinRole> RequireRole<R> {
    pub fn ctx(&self) -> OrgCtx {
        self.0
    }
}

impl<R: MinRole> Deref for RequireRole<R> {
    type Target = OrgCtx;

    fn deref(&self) -> &OrgCtx {
        &self.0
    }
}

impl<S: Send + Sync, R: MinRole> FromRequestParts<S> for RequireRole<R> {
    type Rejection = AppError;

    async fn from_request_parts(parts: &mut Parts, state: &S) -> Result<Self, Self::Rejection> {
        let ctx = OrgCtx::from_request_parts(parts, state).await?;
        ctx.require(R::ROLE)?;
        Ok(RequireRole(ctx, PhantomData))
    }
}

/// Per-request id (generated by the shell; echoed as `x-request-id`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RequestId(pub String);

impl<S: Send + Sync> FromRequestParts<S> for RequestId {
    type Rejection = std::convert::Infallible;

    async fn from_request_parts(parts: &mut Parts, _state: &S) -> Result<Self, Self::Rejection> {
        Ok(parts.extensions.get::<RequestId>().cloned().unwrap_or_else(|| RequestId(String::new())))
    }
}

/// Client address: the rightmost `X-Forwarded-For` hop (appended by Google's front end), else
/// the TCP peer; inserted by the shell for every route.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ClientIp(pub Option<IpAddr>);

impl<S: Send + Sync> FromRequestParts<S> for ClientIp {
    type Rejection = std::convert::Infallible;

    async fn from_request_parts(parts: &mut Parts, _state: &S) -> Result<Self, Self::Rejection> {
        Ok(parts.extensions.get::<ClientIp>().copied().unwrap_or(ClientIp(None)))
    }
}

/// Audit facts of a request.
pub fn request_meta(parts_ext: &axum::http::Extensions, headers: &HeaderMap) -> RequestMeta {
    RequestMeta {
        ip: parts_ext.get::<ClientIp>().and_then(|c| c.0),
        user_agent: headers.get(header::USER_AGENT).and_then(|v| v.to_str().ok()).map(|s| s.chars().take(512).collect()),
        request_id: parts_ext.get::<RequestId>().map(|r| r.0.clone()).filter(|r| !r.is_empty()),
    }
}

/// [`RequestMeta`] as an extractor.
pub struct Meta(pub RequestMeta);

impl<S: Send + Sync> FromRequestParts<S> for Meta {
    type Rejection = std::convert::Infallible;

    async fn from_request_parts(parts: &mut Parts, _state: &S) -> Result<Self, Self::Rejection> {
        Ok(Meta(request_meta(&parts.extensions, &parts.headers)))
    }
}

