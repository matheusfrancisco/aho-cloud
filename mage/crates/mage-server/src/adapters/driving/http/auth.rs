//! Session credential group (server.md "Sessions", "CSRF", "Org selection", "RBAC", UC1, UC2):
//! extractors other areas use, the session/CSRF/org middleware the shell applies to the
//! `/api` and `/events` groups, the `/auth/*` login routes and `/.well-known/mage/keys.json`.
//!
//! Extractors read request extensions set by the middleware, so a router only sees them when
//! the shell put it in a session group (tests insert them with `axum::Extension`):
//! [`Authed`] (missing → 401), [`OrgCtx`] (missing → 404), [`RequireRole`], [`RequestId`],
//! [`ClientIp`].

