/// Public Ed25519 keys (RFC 8037 OKP JWK set with `state`) for verifiers outside the server.
pub fn keys_router(signer: Arc<dyn TokenSigner>) -> Router {
    Router::new().route(KEYS_PATH, get(keys)).with_state(signer)
}

pub fn jwk_set(signer: &dyn TokenSigner) -> JwkSet {
    let keys = signer
        .public_keys()
        .into_iter()
        .filter_map(|k| {
            let state = match k.state {
                SecretState::Staged => KeyState::Staged,
                SecretState::Active => KeyState::Active,
                SecretState::Retired => KeyState::Retired,
                SecretState::Destroyed => return None,
            };
            Some(Jwk::ed25519(k.kid, &k.public_key, state))
        })
        .collect();
    JwkSet { keys }
}

async fn keys(State(signer): State<Arc<dyn TokenSigner>>) -> Response {
    let mut response = Json(jwk_set(signer.as_ref())).into_response();
    response.headers_mut().insert(header::CACHE_CONTROL, HeaderValue::from_static("public, max-age=300"));
    response
}
