/// First value of cookie `name` across `Cookie` headers.
pub fn cookie<'a>(headers: &'a HeaderMap, name: &str) -> Option<&'a str> {
    headers
        .get_all(header::COOKIE)
        .iter()
        .filter_map(|v| v.to_str().ok())
        .flat_map(|v| v.split(';'))
        .filter_map(|pair| pair.trim().split_once('='))
        .find(|(k, _)| *k == name)
        .map(|(_, v)| v.trim())
}

/// `Set-Cookie` for a `__Host-` cookie: Secure, HttpOnly, SameSite=Lax, Path=/, no Domain.
pub fn host_cookie(name: &str, value: &str, max_age_secs: i64) -> HeaderValue {
    let max_age = max_age_secs.max(0);
    HeaderValue::from_str(&format!("{name}={value}; Max-Age={max_age}; Path=/; Secure; HttpOnly; SameSite=Lax"))
        .unwrap_or_else(|_| HeaderValue::from_static("__invalid=; Max-Age=0"))
}

fn clear_cookie(name: &str) -> HeaderValue {
    host_cookie(name, "", 0)
}

fn session_cookie_header(cookie: &SessionCookie, now: time::OffsetDateTime) -> HeaderValue {
    host_cookie(SESSION_COOKIE, &cookie.value, (cookie.expires_at - now).whole_seconds())
}

