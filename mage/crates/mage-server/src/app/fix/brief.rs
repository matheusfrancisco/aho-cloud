//! `fix::brief::render` (fix.md F1 "Template"): the fix brief markdown. Pure, deterministic,
//! plain string building; golden-tested (`testdata/brief/*.md`).

use std::fmt::Write as _;

use mage_core::domain::fix::LockfilePolicy;
use mage_core::domain::recipe::RecipeSpec;
use mage_core::domain::{ArtifactId, Citation, CommitSha, FailureSignature, Matcher, ReproMethod, RunId, ScriptKind, SignatureKind};
use url::Url;

use crate::app::fix::text::{cap_chars, cell, code, fence, neutralize_mentions, permalink, quote, short, ui_link, untrusted};

/// Ticket body characters quoted in "Problem".
pub const TICKET_BODY_CHARS: usize = 600;
/// Cap on any untrusted agent text (summary, suggestion, explanation, notes).
pub const AGENT_TEXT_CHARS: usize = 4000;
/// Built-in generated paths (fix.md "Path policy").
pub const BUILTIN_GENERATED: [&str; 7] = ["dist/", "build/", "target/", ".next/", "node_modules/", "*.min.js", "__generated__/"];

/// The repro script as the brief shows it.
#[derive(Debug, Clone)]
pub struct BriefScript<'a> {
    pub artifact: ArtifactId,
    /// Artifact file name, e.g. `repro.spec.ts`.
    pub name: &'a str,
    pub kind: ScriptKind,
    /// Where to save it in a checkout: `.mage/repro/{cause_id}/{name}`.
    pub path: &'a str,
    /// Inlined body; `None` when larger than the inline limit (link only).
    pub body: Option<&'a str>,
    pub bytes: u64,
}

impl BriefScript<'_> {
    /// fix.md: Playwright → `npx playwright test <path>`, Shell → `bash <path>`.
    pub fn command(&self) -> String {
        script_command(self.kind, self.path)
    }
}

pub fn script_command(kind: ScriptKind, path: &str) -> String {
    match kind {
        ScriptKind::Playwright => format!("npx playwright test {path}"),
        ScriptKind::Shell => format!("bash {path}"),
    }
}

/// Everything `render` needs; all text fields are raw (render sanitises).
#[derive(Debug, Clone)]
pub struct BriefInput<'a> {
    pub ui_url: &'a Url,
    pub github_web: &'a Url,
    pub ticket_identifier: &'a str,
    pub ticket_url: &'a Url,
    pub ticket_title: &'a str,
    pub ticket_body: &'a str,
    pub cause_title: &'a str,
    pub cause_explanation: &'a str,
    pub method: ReproMethod,
    pub owner: &'a str,
    pub name: &'a str,
    pub sha: CommitSha,
    pub assumed: bool,
    pub diagnose_run: RunId,
    pub diagnose_summary: &'a str,
    pub suggested_fix: Option<&'a str>,
    /// Checked cause evidence (printed in "Evidence").
    pub evidence: &'a [Citation],
    /// Checked likely edit sites.
    pub fix_sites: &'a [Citation],
    pub video: Option<ArtifactId>,
    pub trace: Option<ArtifactId>,
    pub signature: &'a FailureSignature,
    pub script: BriefScript<'a>,
    pub recipe: &'a RecipeSpec,
    pub allow_workflow_edits: bool,
    pub lockfiles: LockfilePolicy,
}

pub fn signature_kind(kind: SignatureKind) -> &'static str {
    match kind {
        SignatureKind::AssertionText => "assertion_text",
        SignatureKind::HttpStatus => "http_status",
        SignatureKind::ErrorString => "error_string",
        SignatureKind::ExitCode => "exit_code",
    }
}

pub fn matcher_name(m: Matcher) -> &'static str {
    match m {
        Matcher::Exact => "exact",
        Matcher::Contains => "contains",
        Matcher::Regex => "regex",
    }
}

fn method_name(m: ReproMethod) -> &'static str {
    match m {
        ReproMethod::Ui => "ui",
        ReproMethod::Api => "api",
        ReproMethod::Job => "job",
        ReproMethod::Unknown => "unknown",
    }
}

fn script_lang(kind: ScriptKind, name: &str) -> &'static str {
    match kind {
        ScriptKind::Shell => "bash",
        ScriptKind::Playwright if name.ends_with(".ts") => "ts",
        ScriptKind::Playwright => "js",
    }
}

fn kind_label(kind: ScriptKind) -> &'static str {
    match kind {
        ScriptKind::Playwright => "Playwright",
        ScriptKind::Shell => "Shell",
    }
}

/// Plain prose from a user or agent outside a quote: HTML stripped, mentions neutralised.
fn prose(s: &str, max: usize) -> String {
    untrusted(s, max)
}

fn citation_link(input: &BriefInput<'_>, c: &Citation) -> String {
    let label = format!("{}:{}-{}", c.path, c.lines.start(), c.lines.end());
    format!("[{}]({})", code(&label), permalink(input.github_web, input.owner, input.name, &c.sha, &c.path, &c.lines))
}

pub fn render(input: &BriefInput<'_>) -> String {
    let mut md = String::with_capacity(8 * 1024);
    let r = input.recipe;
    let ui = |path: &str| ui_link(input.ui_url, path);

    // Title and provenance.
    let _ = writeln!(md, "# Fix brief: {} — {}", cell(input.ticket_identifier), prose(input.cause_title, 200));
    md.push('\n');
    let assumed = if input.assumed { " (assumed: default branch head)" } else { "" };
    let _ = writeln!(md, "> Generated by Mage from a **reproduced** diagnosis. Repo `{}/{}` at", input.owner, input.name);
    let _ = writeln!(md, "> `{}`{assumed}.", short(&input.sha));
    let _ = writeln!(md, "> Mage run: {} · Linear: {}", ui(&format!("runs/{}", input.diagnose_run)), input.ticket_url);
    md.push('\n');

    // Problem.
    md.push_str("## Problem\n");
    let _ = writeln!(md, "{}", prose(input.ticket_title, 300));
    let body = untrusted(input.ticket_body, TICKET_BODY_CHARS);
    if !body.is_empty() {
        let _ = writeln!(md, "{}", quote(&body));
    }
    md.push('\n');

    // Root cause.
    md.push_str("## Root cause\n");
    let _ = writeln!(md, "{}", prose(input.cause_explanation, AGENT_TEXT_CHARS));
    md.push('\n');
    md.push_str("Diagnosis summary (from the diagnosing agent):\n");
    let _ = writeln!(md, "{}", quote(&untrusted(input.diagnose_summary, AGENT_TEXT_CHARS)));
    md.push('\n');

    // Evidence.
    md.push_str("## Evidence\n| # | Location | Why |\n|---|---|---|\n");
    for (i, c) in input.evidence.iter().enumerate() {
        let why = c.note.as_deref().map(|n| cell(&untrusted(n, 200))).unwrap_or_default();
        let _ = writeln!(md, "| {} | {} | {why} |", i + 1, citation_link(input, c));
    }
    let mut repro = Vec::new();
    if let Some(v) = input.video {
        repro.push(format!("video {}", ui(&format!("artifacts/{v}"))));
    }
    if let Some(t) = input.trace {
        repro.push(format!("trace {}", ui(&format!("artifacts/{t}"))));
    }
    if !repro.is_empty() {
        let _ = writeln!(md, "\nRepro evidence: {}", repro.join(" · "));
    } else {
        md.push('\n');
    }
    let sig = input.signature;
    let _ = writeln!(
        md,
        "Observed failure: {} {} {}",
        code(signature_kind(sig.kind)),
        matcher_name(sig.matcher),
        code(&neutralize_mentions(&cap_chars(&sig.value, 1024)))
    );
    md.push('\n');

    // Repro script.
    let s = &input.script;
    md.push_str("## Repro script\n");
    let _ = writeln!(md, "{} ({}, method `{}`), saved as {}", code(s.name), kind_label(s.kind), method_name(input.method), code(s.path));
    match s.body {
        Some(body) => {
            let _ = writeln!(md, "{}", fence(script_lang(s.kind, s.name), body));
        }
        None => {
            let _ = writeln!(md, "The script is {} bytes, too large to inline. Download it: {}", s.bytes, ui(&format!("artifacts/{}", s.artifact)));
        }
    }
    md.push('\n');

    // How to run it.
    md.push_str("## How to run it\n");
    let _ = writeln!(md, "1. Check out `{}` (or your branch based on it).", input.sha);
    md.push_str("2. Bring the app up with the recipe `.mage/env.toml`:\n");
    if !r.build.is_empty() {
        let steps: Vec<String> = r.build.iter().map(|b| code(&b.run)).collect();
        let _ = writeln!(md, "   - build: {}", steps.join(" → "));
    }
    for (name, svc) in &r.services {
        let ports = if svc.ports.is_empty() { String::new() } else { format!(" on port {}", svc.ports.iter().map(|p| code(p)).collect::<Vec<_>>().join(", ")) };
        let health = svc.health.as_ref().and_then(|h| {
            h.http.as_ref().map(|u| format!("GET {u}")).or_else(|| h.tcp.as_ref().map(|t| format!("tcp {t}"))).or_else(|| h.command.clone())
        });
        let health = health.map(|h| format!(" (health: {})", code(&h))).unwrap_or_default();
        let _ = writeln!(md, "   - services: {}{ports}{health}", code(name));
    }
    if let Some(db) = &r.database {
        let steps: Vec<String> = db.migrate.iter().chain(db.seed.iter()).map(|c| code(c)).collect();
        let tail = if steps.is_empty() { String::new() } else { format!(": {}", steps.join(" then ")) };
        let _ = writeln!(md, "   - database: {}{tail}", code(&db.engine));
    }
    let mut contract = Vec::new();
    if let Some(b) = &r.browser {
        contract.push(code(&format!("MAGE_BASE_URL={}", b.base_url)));
    }
    contract.push(code("MAGE_PORT_<NAME>"));
    if r.database.is_some() {
        contract.push(code("MAGE_DB_URL"));
    }
    let login = r.browser.as_ref().and_then(|b| b.login.as_ref()).is_some();
    let mut line = format!("3. Export the repro env contract: {}", contract.join(", "));
    if login {
        line.push_str(", `MAGE_LOGIN_URL` / `MAGE_LOGIN_USER` / `MAGE_LOGIN_PASSWORD` (fake test login from the recipe)");
    }
    if !r.env.is_empty() {
        let env: Vec<String> = r.env.iter().map(|(k, v)| code(&format!("{k} = \"{v}\""))).collect();
        let _ = write!(line, ", plus the recipe `[env]` mappings {}", env.join(", "));
    }
    let _ = writeln!(md, "{line}");
    let _ = writeln!(md, "4. Run: {}  → today it **fails** with the signature above.", code(&s.command()));
    let test = r.test.as_ref().map(|t| t.run.as_str());
    match test {
        Some(t) => {
            let _ = writeln!(md, "5. Project tests: {}", code(t));
        }
        None => md.push_str("5. Project tests: none configured in the recipe.\n"),
    }
    md.push('\n');

    // Suggested approach.
    md.push_str("## Suggested approach\n");
    let suggestion = input.suggested_fix.map(|s| untrusted(s, AGENT_TEXT_CHARS)).filter(|s| !s.is_empty());
    let _ = writeln!(md, "{}", quote(suggestion.as_deref().unwrap_or("No suggestion recorded; start at evidence #1.")));
    if !input.fix_sites.is_empty() {
        let sites: Vec<String> = input.fix_sites.iter().map(|c| citation_link(input, c)).collect();
        let _ = writeln!(md, "\nLikely edit sites: {}", sites.join(", "));
    }
    md.push('\n');

    // Acceptance criteria.
    md.push_str("## Acceptance criteria\n");
    let _ = writeln!(
        md,
        "- [ ] The repro script above **passes** (exit 0) and the failure {} no longer appears.",
        code(&neutralize_mentions(&cap_chars(&sig.value, 1024)))
    );
    if let Some(t) = test {
        let _ = writeln!(md, "- [ ] {} exits 0.", code(t));
    }
    if let Some(lint) = r.fix.as_ref().and_then(|f| f.lint.as_deref()) {
        let _ = writeln!(md, "- [ ] {} exits 0.", code(lint));
    }
    md.push('\n');

    // Constraints.
    md.push_str("## Constraints\n");
    md.push_str("- Keep the change minimal and local to the root cause; no unrelated refactors.\n");
    md.push_str("- Do not modify the repro script or weaken its assertions; do not edit `.mage/`.\n");
    match input.lockfiles {
        LockfilePolicy::WithManifest => md.push_str("- Do not change lockfiles unless you change the matching dependency manifest.\n"),
        LockfilePolicy::Exclude => md.push_str("- Do not change lockfiles; lockfile changes are discarded.\n"),
        LockfilePolicy::Include => {}
    }
    let mut generated: Vec<String> = BUILTIN_GENERATED.iter().map(|g| code(g)).collect();
    if let Some(fix) = &r.fix {
        generated.extend(fix.generated.iter().map(|g| code(g)));
    }
    let _ = writeln!(md, "- Do not edit generated files ({}); change their source instead.", generated.join(", "));
    if !input.allow_workflow_edits {
        md.push_str("- Do not edit `.github/workflows/` or `.github/actions/`.\n");
    }
    md.push_str("- Never add credentials, tokens or real keys; the recipe uses fake keys only.\n");
    md
}

