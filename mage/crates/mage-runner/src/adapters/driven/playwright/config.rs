//! The generated `mage.config.mjs` (executor.md "Generated config"). Every value is JSON-encoded
//! by Rust, so script names, grep patterns, or URLs cannot inject code.

use std::fmt::Write as _;

use crate::ports::browser::{RecordOpts, ScreenshotMode};

pub const CONFIG_FILE: &str = "mage.config.mjs";
pub const REPORT_FILE: &str = "report.json";
pub const OUTPUT_DIR: &str = "out";
pub const HAR_FILE: &str = "out/network.har";
pub const TESTS_DIR: &str = "tests";

/// Inputs of one config beyond `RecordOpts`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ConfigInputs<'a> {
    /// `Env::render(recipe.browser.base_url)`; `None` leaves `baseURL` undefined.
    pub base_url: Option<&'a str>,
    /// `BrowserScript.grep`, compiled as a JS `RegExp`.
    pub grep: Option<&'a str>,
    /// `false` adds `launchOptions: { chromiumSandbox: false }` (enforced-mode namespaces).
    pub chromium_sandbox: bool,
}

fn js(value: &str) -> String {
    // A JSON string is a valid JS string literal; U+2028/U+2029 are escaped by serde_json since
    // they would end a line in older JS parsers? They are not, so escape them explicitly.
    serde_json::to_string(value).unwrap_or_else(|_| "\"\"".to_owned()).replace('\u{2028}', "\\u2028").replace('\u{2029}', "\\u2029")
}

fn millis(d: std::time::Duration) -> u128 {
    d.as_millis()
}

pub fn render_config(opts: &RecordOpts, inputs: &ConfigInputs<'_>) -> String {
    let mut out = String::with_capacity(1024);
    out.push_str("// generated by mage; do not edit\n");
    out.push_str("import { defineConfig } from '@playwright/test';\n");
    out.push_str("export default defineConfig({\n");
    let _ = writeln!(out, "  testDir: {},", js(&format!("./{TESTS_DIR}")));
    let _ = writeln!(out, "  outputDir: {},", js(&format!("./{OUTPUT_DIR}")));
    let _ = writeln!(out, "  timeout: {},", millis(opts.test_timeout));
    let _ = writeln!(out, "  globalTimeout: {},", millis(opts.timeout));
    out.push_str("  expect: { timeout: 10000 },\n");
    out.push_str("  retries: 0,\n");
    out.push_str("  workers: 1,\n");
    out.push_str("  fullyParallel: false,\n");
    let _ = writeln!(out, "  reporter: [['json', {{ outputFile: {} }}], ['line']],", js(&format!("./{REPORT_FILE}")));
    match inputs.grep {
        Some(pattern) => {
            let _ = writeln!(out, "  grep: new RegExp({}),", js(pattern));
        }
        None => out.push_str("  grep: undefined,\n"),
    }
    out.push_str("  use: {\n");
    match inputs.base_url {
        Some(url) => {
            let _ = writeln!(out, "    baseURL: {},", js(url));
        }
        None => out.push_str("    baseURL: undefined,\n"),
    }
    out.push_str("    headless: true,\n");
    let _ = writeln!(out, "    video: '{}',", if opts.video { "on" } else { "off" });
    let _ = writeln!(out, "    trace: '{}',", if opts.trace { "on" } else { "off" });
    let screenshot = match opts.screenshots {
        ScreenshotMode::Off => "off",
        ScreenshotMode::OnFailure => "only-on-failure",
        ScreenshotMode::On => "on",
    };
    let _ = writeln!(out, "    screenshot: '{screenshot}',");
    out.push_str("    viewport: { width: 1280, height: 800 },\n");
    out.push_str("    ignoreHTTPSErrors: true,\n");
    if opts.har {
        let _ = writeln!(out, "    contextOptions: {{ recordHar: {{ path: {}, content: 'omit' }} }},", js(&format!("./{HAR_FILE}")));
    }
    if !inputs.chromium_sandbox {
        out.push_str("    launchOptions: { chromiumSandbox: false },\n");
    }
    out.push_str("  },\n");
    out.push_str("  projects: [{ name: 'chromium', use: { browserName: 'chromium' } }],\n");
    out.push_str("});\n");
    out
}

#[cfg(test)]
mod tests {
    use std::path::PathBuf;
    use std::time::Duration;

    use super::*;

    fn opts() -> RecordOpts {
        RecordOpts {
            video: true,
            trace: false,
            screenshots: ScreenshotMode::OnFailure,
            har: true,
            timeout: Duration::from_secs(180),
            test_timeout: Duration::from_secs(120),
            outbox: PathBuf::from("/tmp/outbox"),
            label: "explore-1".into(),
        }
    }

    #[test]
    fn renders_record_options_and_timeouts() {
        let cfg = render_config(&opts(), &ConfigInputs { base_url: Some("http://127.0.0.1:43123"), grep: None, chromium_sandbox: true });
        assert!(cfg.contains("timeout: 120000,"));
        assert!(cfg.contains("globalTimeout: 180000,"));
        assert!(cfg.contains("video: 'on',"));
        assert!(cfg.contains("trace: 'off',"));
        assert!(cfg.contains("screenshot: 'only-on-failure',"));
        assert!(cfg.contains("baseURL: \"http://127.0.0.1:43123\","));
        assert!(cfg.contains("recordHar: { path: \"./out/network.har\", content: 'omit' }"));
        assert!(cfg.contains("outputFile: \"./report.json\""));
        assert!(cfg.contains("grep: undefined,"));
        assert!(!cfg.contains("chromiumSandbox"));
        let off = RecordOpts { har: false, ..opts() };
        let cfg = render_config(&off, &ConfigInputs { base_url: None, grep: None, chromium_sandbox: false });
        assert!(!cfg.contains("recordHar"));
        assert!(cfg.contains("baseURL: undefined,"));
        assert!(cfg.contains("launchOptions: { chromiumSandbox: false },"));
    }

    #[test]
    fn hostile_values_stay_inside_string_literals() {
        let grep = "x\"); require('child_process').execSync('touch /tmp/pwned'); (\"";
        let url = "http://127.0.0.1:1/'}); process.exit(0); ({'\u{2028}";
        let cfg = render_config(&opts(), &ConfigInputs { base_url: Some(url), grep: Some(grep), chromium_sandbox: true });
        let grep_line = cfg.lines().find(|l| l.trim_start().starts_with("grep:")).unwrap();
        assert_eq!(grep_line, format!("  grep: new RegExp({}),", serde_json::to_string(grep).unwrap()));
        // The literal parses back to the exact input.
        let literal = grep_line.trim_start().trim_start_matches("grep: new RegExp(").trim_end_matches("),");
        assert_eq!(serde_json::from_str::<String>(literal).unwrap(), grep);
        let url_line = cfg.lines().find(|l| l.trim_start().starts_with("baseURL:")).unwrap();
        assert!(url_line.contains("\\u2028"), "line separators escaped: {url_line}");
        assert_eq!(cfg.lines().count(), render_config(&opts(), &ConfigInputs { base_url: None, grep: None, chromium_sandbox: true }).lines().count());
    }
}
