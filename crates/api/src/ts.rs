//! TypeScript for the API bodies. Contract types are imported from `./contract`.

use cloud_contract::ts::push;

use crate::*;

pub const HEADER: &str = "// @generated by cloud-api tests (UPDATE_GENERATED=1 cargo test -p cloud-api). Do not edit.\n\n";

pub fn typescript() -> String {
    let cfg = cloud_contract::ts::config();
    let mut body = String::new();
    macro_rules! all {
        ($($t:ty),* $(,)?) => { $( push::<$t>(&mut body, &cfg); )* };
    }
    all!(
        ApiError,
        DeviceStart,
        DeviceStarted,
        DeviceApprove,
        DevicePoll,
        DevicePolled,
        PasskeyChallenge,
        PasskeyRegisterStart,
        PasskeyLoginStart,
        PasskeyFinish,
        Session,
        User,
        Me,
        Membership,
        CreateOrg,
        Org,
        Member,
        AddMember,
        SetPolicy,
        CreateProject,
        Project,
        StageHead,
        ArchiveUploaded,
        SessionUploaded,
        CheckManifest,
        CheckResult,
        ProposeRelease,
        ReleaseStatus,
        Release,
        ApprovalView,
        ApprovalProof,
        Approve,
        Reject,
        Promote,
        Rollback,
        GrantStandingOrders,
        OnCall,
        AddDomain,
        DomainState,
        DnsRecord,
        DomainView,
        SetSecret,
        SecretView,
        Workspace,
        LedgerEntry,
    );
    let contract = cloud_contract::ts::typescript();
    let names: Vec<&str> = contract
        .lines()
        .filter_map(|l| l.strip_prefix("export type "))
        .filter_map(|l| l.split([' ', '<']).next())
        .filter(|name| uses(&body, name))
        .collect();
    let mut out = String::from(HEADER);
    out.push_str(&format!("import type {{ {} }} from \"./contract\";\n\n", names.join(", ")));
    out.push_str(&body);
    out.push_str(&routes_ts());
    out
}

fn routes_ts() -> String {
    use crate::routes::*;
    let mut out = String::from("export const routes = {\n");
    macro_rules! all {
        ($($name:ident),* $(,)?) => { $( out.push_str(&format!("  {}: {:?},\n", stringify!($name), $name)); )* };
    }
    all!(
        DEVICE_START,
        DEVICE_APPROVE,
        DEVICE_POLL,
        PASSKEY_REGISTER_START,
        PASSKEY_REGISTER_FINISH,
        PASSKEY_LOGIN_START,
        PASSKEY_LOGIN_FINISH,
        ME,
        ORGS,
        ORG_MEMBERS,
        ORG_POLICY,
        ORG_PROJECTS,
        PROJECT,
        ARCHIVES,
        SESSIONS,
        MANIFEST_CHECK,
        RELEASES,
        RELEASE,
        APPROVE,
        REJECT,
        PROMOTE,
        ROLLBACK,
        STANDING_ORDERS,
        ONCALL,
        DOMAINS,
        DOMAIN_VERIFY,
        WORKSPACES,
        LEDGER,
        SECRETS,
    );
    out.push_str("} as const;\n\n");
    out.push_str(
        "/** Fills `{name}` placeholders, URI-encoding each value. */\n\
         export function fill(template: string, args: Record<string, string>): string {\n  \
         return template.replace(/\\{(\\w+)\\}/g, (_, k: string) => encodeURIComponent(args[k] ?? \"\"));\n}\n",
    );
    out
}

/// `name` appears in `text` as a whole identifier.
fn uses(text: &str, name: &str) -> bool {
    let ident = |c: char| c.is_ascii_alphanumeric() || c == '_';
    text.match_indices(name).any(|(i, _)| {
        let before = text[..i].chars().next_back();
        let after = text[i + name.len()..].chars().next();
        !before.is_some_and(ident) && !after.is_some_and(ident)
    })
}
